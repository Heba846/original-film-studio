#!/usr/bin/env python3
"""Render edition20/FLOW_JOBS_NEXT.md from flow_jobs.json + budget_ledger.json + the built timeline.
Never edit the .md by hand. Run tools/film_build.py first so placements are current."""
import json
from collections import defaultdict
from pathlib import Path
R = Path(__file__).resolve().parent.parent
J = json.loads((R / "edition20/flow_jobs.json").read_text())
L = json.loads((R / "edition20/budget_ledger.json").read_text())
T = json.loads((R / "src/film/data/film_timeline.json").read_text())
pr = L["pricing"]; per = pr["credits_per_output"] * pr["outputs_per_prompt"]
place = defaultdict(list)
for c in T["cuts"]:
    if c.get("kind") == "flow_job":
        place[c["shot"]].append(c)

def placements(jid):
    rows = []
    for c in place[jid]:
        tag = "memory" if c.get("memory") else ("reuse" if c.get("is_reuse") else "first use")
        rows.append(f"{c['seg']} {c['dur']/24:.2f}s src {c['src_in']:.2f}-{c['src_out']:.2f} @{c['rate']:.3f}x ({tag}, use #{c['use_no']})")
    return rows

jobs = J["jobs"]
b1 = [j for j in jobs if j["batch"] == 1]
out = ["# Flow generation jobs - plan v2 (next actions)", "",
 "Generated by `tools/flow_sheet.py` from `flow_jobs.json`, `budget_ledger.json` and the built timeline. "
 "**No generation has been run from the cloud session; 0 credits spent.**", "",
 f"70 jobs x {per} cr = {70*per} cr primary; retakes pool {L['pools']['retakes']}; reserve {L['pools']['reserve_unspent']} (unspent). "
 "U01 (Theo's arrest) is a non-photoreal code scene (`CODE_ARREST`), not a paid job.", "",
 "## Before Batch 1 (owner, in Flow)",
 "1. Pick the model used for the approved painterly hospital clip. Read the per-output price Flow shows.",
 "2. Record it in `edition20/budget_ledger.json` (`model_name_in_flow`, `credits_per_output`, `confirmed_in_flow_ui: true`, `confirmed_on`).",
 "3. Set **outputs per prompt = 1** (at 2, every job costs double).",
 "4. `python3 tools/validate_budget.py` must print `spending authorized by ledger: YES`.",
 "5. Upload `edition20/flow_refs/REF_*.png` as ingredients/frames (uploads are free; generated reference images are charged to the primary pool).", "",
 f"## Batch 1 - CH00 + CH01 - {len(b1)} jobs - {per*len(b1)} credits (assumed price)", "",
 "Every job lists where its frames land: seconds on screen, the source range it must supply (inside 0.20-7.70 s of an ~7.9 s result) and the speed. "
 "If a delivered take is shorter or has bad frames in that range, re-plan before approving.", ""]
for j in b1:
    out += [f"### {j['job_id']} `{j['slug']}` - {j['category']} - {j['continuity_phase']} - {j['chapter']}",
            f"**Event:** {j['narrative_event']}  ", f"**Replaces:** {j['replaces']} - **mouth:** {j['mouth']} - **decisive action:** {'yes' if j['decisive'] else 'no'}  ",
            f"**Save as:** `public/flow/{j['job_id']}.mp4`  ", "**Placements:**", *[f"- {p}" for p in placements(j["job_id"])], "",
            "```text", j["prompt"], "```", ""]
out += ["## Opening corrections built into Batch 1",
 "- `aftermath_wide` replaces garage.mp4: Nico upright beside the silver sedan, Frankie a DIFFERENT man (good dark overcoat, face away), nobody treated or bandaged in the garage, pooled water not falling rain, no smoke.",
 "- Weapons split out so three-person geography stays simple: `frankie_hand` (second gun a foot from his hand) and `nico_hands` (splint right, gun left). Same 70-job budget.",
 "- `nico_ots` replaces nico.mp4: over IVY's shoulder (red bun with pen, navy shoulder), Nico finds HER eyes, mouth closed. n004's existing WAV is placed on it for 'Go back inside, Dr. Marlowe.'",
 "- `ivy_reaction` is the listener shot: the cut lands on her for 'You were never here.' No lip-sync is claimed from silent footage.",
 "- Wardrobe lock P0: Nico ruined charcoal suit over a black shirt (jacket off in Bay 14, matching the approved hospital clip); healed white scar anatomical LEFT brow; white plaster splint anatomical RIGHT; Ivy no ring/chain.", "",
 "## Review checklist (every result, before it can be approved)",
 "- [ ] Same faces as `REF_ivy_face_hospital_1s.png` / `REF_nico_face_hospital_7s.png`.",
 "- [ ] Nico: injured arm anatomical RIGHT; healed WHITE scar through anatomical LEFT eyebrow, no fresh cut. Never fix by mirroring.",
 "- [ ] Phase lock for the date (see `LOCK` in each intent): ring/chain, splint colour, wardrobe.",
 "- [ ] Indoors = no falling rain. No readable text, clocks, signs, plates or logos.",
 "- [ ] Nobody is shown firing at 4:10. Roles and positions stay fixed; no morphing or smoke.",
 "- [ ] Mouths closed where the job says so.",
 "- [ ] The placement's source range is clean (no bad first/last frames inside it).",
 "- Verdict: set the shot's `status` in `media_manifest.json` (`approved` / `rejected`), add a ledger entry, run `python3 tools/film_build.py`.", "",
 "## Retake policy (200-credit pool)",
 "- Only for a checklist failure; max 2 retakes per job; logged with pool `retake`.",
 "- After two failures, re-plan the shot as a reaction/insert, a motivated reuse or a code beat instead of a third spend.", "",
 "## Batches 2-4 (intent + continuity lock; full prompts written after Batch 1 review)", "",
 "| Job | Slug | Batch | Phase | Event | Placements |", "|---|---|---|---|---|---|"]
for j in jobs:
    if j["batch"] > 1:
        out.append(f"| {j['job_id']} | `{j['slug']}` | {j['batch']} | {j['continuity_phase']} | {j['narrative_event']} | {'; '.join(placements(j['job_id']))} |")
out += ["", f"Category split: {J['category_counts']}. Rebalanced from v1 by need, not by ratio: dialogue scenes need listener shots; "
        "the second half (CH08-CH19) now gets 35 of 70 jobs instead of 31."]
(R / "edition20/FLOW_JOBS_NEXT.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print("written", len(jobs), "jobs")
